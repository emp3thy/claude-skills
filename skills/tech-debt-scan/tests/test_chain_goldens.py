GOLDEN = Path(__file__).parent / "golden"
CORPUS = Path(__file__).parent / "fixtures" / "corpus"
FIXTURES = ("service-py", "web-ts", "mixed-decoys")
UPDATE = os.environ.get("UPDATE_GOLDENS") == "1"
# The first live run's date: keeping it fixed keeps the day counts, and so the
# fingerprints, that rules.py derives from "now" identical on every later run.
RULES_NOW = datetime(2026, 9, 5, tzinfo=UTC)
# The render's own clock. ``design.md`` prints the scan date in its frontmatter and
# in the ``# Tech-debt scan - <date>`` header, so an unpinned ``date.today()`` would
# put today into every golden and break the byte comparison tomorrow.
SCAN_DATE = "2026-09-06"
# The hand-added finding whose quote is not in the file; the merge must divert it.
PIN_TITLE = "invented quote (golden pin)"
# Live scout findings that cite a quote ``find_quote`` cannot rejoin. The round-0
# misses all spanned more lines than the fallback window and were cited a line or
# two off; fix round 1 widened that window to the quote's own line count and every
# one of them rejoined. The one that remains is a different failure: the second
# web-ts run quoted ``getJson`` with an interior line (``return await
# response.json();``) silently dropped, and no window recovers a quote whose middle
# is missing. The tables are kept (empty where they are empty) so a new unverifiable
# quote fails the test rather than passing as noise. ``diverted`` findings lose every
# quote and land in ``open_questions``; ``partial`` findings keep another verified
# quote and stay as candidates.
LIVE_QUOTE_MISSES: dict[str, dict[str, frozenset[str]]] = {
    "service-py": {"diverted": frozenset(), "partial": frozenset()},
    "web-ts": {
        "diverted": frozenset({"API client silently swallows fetch errors with no test"}),
        "partial": frozenset(),
    },
    "mixed-decoys": {"diverted": frozenset(), "partial": frozenset()},
}
# Batches the plan asks for that no live run ever produced a verdict file for. A
# verdict cannot be written by hand (it would be invented agent output), so such a
# batch's candidates stay unverified at tier C. The table is empty: fix round 1
# recovered enough quotes to push web-ts into a fifth batch its first live run never
# made, and fix round 2's second web-ts run supplied that batch. Kept (empty) so a
# plan that outgrows its verdicts again fails here rather than passing silently.
UNVERIFIED_BATCHES: dict[str, frozenset[str]] = {
    "service-py": frozenset(),
    "web-ts": frozenset(),
    "mixed-decoys": frozenset(),
}

Chain = tuple[dict[str, Any], dict[str, Any], dict[str, Any]]


def _canon(doc: dict[str, Any], root: str) -> bytes:
    """The document as the golden holds it, with the temporary repository root masked.

    Both spellings are masked: the plain path and the JSON-escaped one a Windows
    root turns into (``C:\\repo`` is written ``C:\\\\repo`` inside a JSON string).
    """
    text = json.dumps(doc, indent=2) + "\n"
    text = text.replace(root.replace("\\", "\\\\"), "<root>").replace(root, "<root>")
    return text.encode("utf-8")


def _check(name: str, doc: dict[str, Any], golden: Path, root: str) -> None:
    got = _canon(doc, root)
    if UPDATE:
        golden.parent.mkdir(parents=True, exist_ok=True)
        golden.write_bytes(got)
    assert golden.is_file(), f"missing golden {golden}"
    assert got == golden.read_bytes(), f"{name} differs from {golden}"


def _check_text(name: str, text: str, golden: Path, root: str) -> None:
    """``_check``'s text twin: same UPDATE_GOLDENS behaviour, same root masking, LF only.

    ``render_design`` already joins its lines with a bare line feed, so the
    string is encoded as it stands and written with ``write_bytes``; nothing
    here may round-trip through text mode, or a Windows checkout would store
    CRLF and never match again.
    The repository root reaches ``design.md`` twice (the frontmatter ``root:``
    key and the ``Scanned `<root>`` header line) and is masked the same two ways
    ``_canon`` masks it, so one helper serves both document kinds.
    """
    masked = text.replace(root.replace("\\", "\\\\"), "<root>").replace(root, "<root>")
    got = masked.encode("utf-8")
    if UPDATE:
        golden.parent.mkdir(parents=True, exist_ok=True)
        golden.write_bytes(got)
    assert golden.is_file(), f"missing golden {golden}"
    assert got == golden.read_bytes(), f"{name} differs from {golden}"


def _chain(name: str, repo: Path, tmp_path: Path) -> Chain:
    workdir = tmp_path / "wd"
    planted = json.loads((CORPUS / name / "planted.json").read_bytes())
    inventory, coupling = build_all(
        repo, churn_months=int(planted["churn_months"]), config=DEFAULTS
    )
    write_outputs(inventory, coupling, workdir)
    # Step 1a (after inventory, before patterns): the concerns scout's definition-name
    # index. Built here, not left absent, so the concerns family's leads are real
    # ``candidate`` entries rather than an empty pool that skips the family outright.
    write_json(workdir / "concern-index.json", build_concern_index(repo, inventory, coupling))
    patterns, inline = run_patterns(repo, inventory, DEFAULTS, blame=False)
    for entry in inventory["files"]:
        entry["inline_disables"] = inline.get(entry["path"], 0)
    write_json(workdir / "inventory.json", inventory)
    write_json(workdir / "patterns.json", patterns)
    findings, leads = run_rules(repo, inventory, DEFAULTS, now=RULES_NOW)
    write_json(
        workdir / "rule-findings.json",
        {"schema_version": 2, "findings": findings, "leads": leads},
    )
    golden = GOLDEN / name
    # Step 4's canned counterpart: the golden tool-signals.json (test_tools_probe.py's
    # own live-probe golden for this fixture) copied into the workdir so an inference
    # signal on a planted file -- the ruff PERF401 hit on the performance family's
    # planted loop -- can earn a candidate the ``tool:`` corroboration token spec 2.3's
    # cap requires. No test-only signal is invented: every entry in this file is real
    # tool output, pinned by test_tools_probe.py against the same corpus files.
    shutil.copy(golden / "tool-signals.json", workdir / "tool-signals.json")
    plan, prompts = build_plan(workdir, DEFAULTS, families="deep", top=5)
    write_plan(workdir, plan, prompts)
    for entry in plan["entries"]:
        src = golden / entry["output"]
        assert src.is_file(), f"golden scout missing for {entry['family']} on {name}"
        dest = workdir / entry["output"]
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(src, dest)
    for extra in sorted((golden / "scouts").glob("*.json")):
        assert extra.name in {Path(e["output"]).name for e in plan["entries"]}, (
            f"golden scout {extra.name} is not in the plan for {name}"
        )
    root = str(repo.resolve())
    candidates = merge(workdir, repo, DEFAULTS)
    write_json(workdir / "candidates.json", candidates)
    _check("candidates", candidates, golden / "candidates.json", root)
    vplan, _ = build_verify_plan(workdir, repo, DEFAULTS, 5)
    _check("verify-plan", vplan, golden / "verify-plan.json", root)
    verdicts: dict[str, list[dict[str, Any]]] = {}
    for batch in vplan["batches"]:
        src = golden / batch["output"]
        if batch["output"] in UNVERIFIED_BATCHES[name]:
            assert not src.is_file(), f"{src} exists; drop it from UNVERIFIED_BATCHES"
            continue
        assert src.is_file(), f"golden verdict missing: {src}"
        verdicts[batch["output"]] = json.loads(src.read_bytes())
    verified = apply(candidates["candidates"], vplan, verdicts)
    # Persisted as well as compared, the way ``candidates.json`` already is: the
    # render stage below reads the whole chain back off disk through
    # ``load_inputs``, so a stage that only ever existed in memory is missing.
    write_json(workdir / "verified.json", verified)
    _check("verified", verified, golden / "verified.json", root)
    ranked = rank(verified, inventory, DEFAULTS, preset="balanced", top=5)
    write_json(workdir / "ranked.json", ranked)
    _check("ranked", ranked, golden / "ranked.json", root)
    # No fixture has a baseline yet (phase 5's ``record`` is Task 3), so every
    # status is NEW and ``baseline_found`` is false -- the point of this golden
    # is that the chain now produces the file ``design_writer`` has been
    # waiting for, not that it changes any classification.
    diff_doc = diff(verified, None, repo, SCAN_DATE)
    write_json(workdir / "diff.json", diff_doc)
    _check("diff", diff_doc, golden / "diff.json", root)
    # The render stage. ``notes.json`` is the one input on this chain that no
    # script produces: it is the remediation agent's reply, so it is hand-written
    # per fixture and copied in exactly as a real run would drop it in the
    # workdir. web-ts deliberately omits its last top-N fingerprint, so the
    # NOTE_PLACEHOLDER path is covered by a real golden rather than a unit stub.
    shutil.copy(golden / "notes.json", workdir / "notes.json")
    write_design(load_inputs(workdir), SCAN_DATE, workdir / "design.md")
    _check_text(
        "design.md",
        (workdir / "design.md").read_bytes().decode("utf-8"),
        golden / "design.md",
        root,
    )
    # findings.json lands in the workdir, never beside --out; that is the contract
    # evaluate.load_findings depends on, so reading it from anywhere else here
    # would let a regression in write_design pass unnoticed.
    _check(
        "findings.json",
        json.loads((workdir / "findings.json").read_bytes()),
        golden / "findings.json",
        root,
    )
    return candidates, verified, ranked


@pytest.mark.parametrize("name", FIXTURES)
def test_chain_matches_goldens_and_meets_the_corpus_bar(
    name: str, request: pytest.FixtureRequest, tmp_path: Path
) -> None:
    repo = request.getfixturevalue(name.replace("-", "_") + "_repo")
    candidates, verified, ranked = _chain(name, repo, tmp_path)
    planted = json.loads((CORPUS / name / "planted.json").read_bytes())
    report = evaluate(verified["findings"], planted, set(ranked["top_n"]), top=5)
    assert report["decoys_in_tier_a"] == 0, report["decoys"]
    assert report["decoys_in_top_n"] == 0, report["decoys"]
    assert report["counts"]["on_planted"] > 0
    diverted = sorted(
        q["question"] for q in candidates["open_questions"] if q["reason"] == "quote not found"
    )
    assert diverted == sorted({PIN_TITLE, *LIVE_QUOTE_MISSES[name]["diverted"]}), diverted
    assert any(f["verdict"] == "reject" and f["trap_matched"] for f in verified["findings"])
    top_n = set(ranked["top_n"])
    assert all(
        f["tier"] in ("A", "B") for f in verified["findings"] if f["fingerprint"] in top_n
    )

    # The rendered document reads back through its own parser on real data.
    workdir = tmp_path / "wd"
    design = workdir / "design.md"
    parsed = parse_design(design)
    assert parsed["metadata"]["schema_version"] == 2
    top_slugs = [f["slug"] for f in parsed["findings"] if f["tier"] in ("A", "B")]
    assert top_slugs and len(top_slugs) == len(set(top_slugs)), "slugs are unique"
    for finding in parsed["findings"]:
        assert finding["category"] == finding["family"]
        assert "# Not assessed" not in finding["body_md"], "the H1 boundary holds on real data"
    # Only a top-N finding gets a Signals section; below-the-cut ones are compact.
    assert set(ranked["top_n"]) >= {
        f["fingerprint"] for f in parsed["findings"] if "### Signals" in f["body_md"]
    }
    # Nothing in the render reads a clock or a random seed of its own: the same
    # workdir at the same pinned scan date renders byte for byte the same document.
    again = tmp_path / "again" / "design.md"
    write_design(load_inputs(workdir), SCAN_DATE, again)
    assert again.read_bytes() == design.read_bytes(), "the render is deterministic"


@pytest.mark.parametrize("name", FIXTURES)
def test_every_golden_quote_except_the_pin_verifies(
    name: str, request: pytest.FixtureRequest
) -> None:
    """Only the pin and the named live misses fail ``find_quote`` against the fixture."""
    from evidence import find_quote
    from merge_findings import _normalise_path

    repo = request.getfixturevalue(name.replace("-", "_") + "_repo")
    diverted: set[str] = set()
    partial: set[str] = set()
    for scout in sorted((GOLDEN / name / "scouts").glob("*.json")):
        for finding in json.loads(scout.read_bytes())["findings"]:
            found = []
            for ev in finding["evidence"]:
                # merge_findings normalises backslashes to forward slashes before
                # verifying a quote, so a golden scout recorded on Windows (a
                # literal "vendor\\x.js") must be resolved the same way here, or
                # the path is read as one Linux filename that never exists.
                path = repo / (_normalise_path(ev["file"]) or ev["file"])
                raw = path.read_bytes() if path.is_file() else b""
                lines = raw.decode("utf-8", "replace").splitlines()
                hit = find_quote(lines, ev["quote"], ev.get("line_start"), ev.get("line_end"))
                found.append(hit is not None)
            if not any(found):
                diverted.add(finding["title"])
            elif not all(found):
                partial.add(finding["title"])
    expected = LIVE_QUOTE_MISSES[name]
    assert diverted == {PIN_TITLE, *expected["diverted"]}, sorted(diverted)
    assert partial == set(expected["partial"]), sorted(partial)


