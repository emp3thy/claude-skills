"""The detect, verify, rank chain over the corpus with canned scouts and verdicts (spec 6, 11).

Scout and verdict files are the first live run's output (plus the hand edits the
phase 2 plan names); every deterministic stage is compared byte for byte to its
golden. Regenerate the deterministic goldens with UPDATE_GOLDENS=1 after an
intentional change; never regenerate the scouts or verdicts by hand.

The chain ends at the render: ``notes.json`` (the remediation agent's reply, the
one input on this chain no script produces) is hand-written per fixture and
copied into the workdir, then ``design.md`` and ``findings.json`` are compared
like every other stage. ``notes.json`` is an input, never regenerated by
UPDATE_GOLDENS; ``design.md`` and ``findings.json`` are outputs and are.

Three clocks are pinned so the goldens stay stable: ``run_patterns`` runs with
``blame=False`` (SATD ages are wall-clock), ``run_rules`` runs at ``RULES_NOW``,
and the render runs at ``SCAN_DATE``. The rule quotes for
``release.stale-env-branch`` and ``ownership.former-contributor`` spell an age in
days, and the fingerprint hashes that quote, so an unpinned clock would give the
same debt a new fingerprint every day; ``design.md`` prints its scan date twice,
so an unpinned render date would put today into the golden.

One finding per fixture (``PIN_TITLE``) is hand-added with a quote that is not in
the file, so the diversion path is exercised on every run. The live scouts of
their own accord produced a few more unverifiable quotes; those are named in
``LIVE_QUOTE_MISSES`` rather than edited out, so the test still states the exact
set of quotes that must fail.

The verdict goldens are the live output, redacted as the harness writes them:
``live_run._write_payload`` walks the array (verifier) contract through
``redaction.redact``, so ``service-py/verdicts/verify-02.json`` was re-redacted
once by hand to match (hand edit 4). The scout goldens are raw, as the harness
writes them: ``merge_findings`` verifies a quote against the file before it
redacts it, so a credential-shaped quote has to stay raw here to be found at all.
"""
